#include "functions.hpp"

double addition(double x, double y){
    return x + y;
}

double subtraction(double x, double y){
    return x - y;
}

double multiplication(double x, double y){
    return x * y;
}

double division(double x, double y){
    return x / y;
}

double power(double x, double y){
    return pow(x,y);
};